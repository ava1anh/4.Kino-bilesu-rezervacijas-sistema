    /**
     * Atgriež atlasītās tabulas rindas identifikatoru (pirmā kolonna).
     *
     * @param table tabula
     * @return identifikators vai -1, ja rinda nav atlasīta
     */
    private int selectedId(JTable table) {
        int row = table.getSelectedRow();
        return row == -1 ? -1 : (int) table.getValueAt(row, 0);
    }

    /**
     * Sagatavo filmu logu pēc veiksmīgas pieslēgšanās atbilstoši lietotāja lomai un atver to.
     */
    private void enterMovieWindow() {
        boolean admin = Session.isAdmin();
        lblWelcome.setText("Sveiki, " + Session.username + (admin ? " (administrators)" : "") + "!");
        lblAdminHint.setText(admin ? "Filmu pārvaldība:" : "Filmu pārvaldība ir pieejama tikai administratoram.");
        for (Component c : new Component[]{txtTitle, txtGenre, txtDuration, txtDescription,
            btnAdd, btnUpdate, btnDelete}) {
            c.setEnabled(admin);
        }
        for (Component c : new Component[]{cmbHall, txtScreeningDate, txtScreeningTime, txtPrice,
            btnAddScreening, btnDeleteScreening}) {
            c.setEnabled(admin);
        }
        btnReserve.setEnabled(!admin);
        txtSearch.setText("");
        loadMovies(null);
        openDialog(MovieDialog, this);
    }

