    /**
     * Parāda norādīto logu ekrāna centrā un paslēpj visus pārējos (vienlaikus redzams tikai viens logs).
     *
     * @param target logs, kas jāparāda
     */
    private void showWindow(Window target) {
        target.pack();
        target.setLocationRelativeTo(null);
        target.setVisible(true);
        if (target != this) {
            setVisible(false);
        }
        for (JDialog dialog : allDialogs()) {
            if (dialog != target) {
                dialog.setVisible(false);
            }
        }
        target.toFront();
    }

    /**
     * Atver apakšlogu un atceras, uz kuru logu jāatgriežas pēc tā aizvēršanas.
     *
     * @param dialog atveramais apakšlogs
     * @param returnTo logs, uz kuru jāatgriežas
     */
    private void openDialog(JDialog dialog, Window returnTo) {
        returnTargets.put(dialog, returnTo);
        showWindow(dialog);
    }

    /**
     * Aizver apakšlogu, attīra tā ievadlaukus un atgriežas iepriekšējā logā.
     *
     * @param dialog aizveramais apakšlogs
     */
    private void closeDialog(JDialog dialog) {
        clearInputs(dialog.getContentPane());
        Window back = returnTargets.getOrDefault(dialog, this);
        showWindow(back);
    }

    private void onDialogClosing(JDialog dialog) {
        if (dialog == MovieDialog) {
            int answer = JOptionPane.showConfirmDialog(dialog, "Vai atteikties no sistēmas?",
                    "Atteikšanās", JOptionPane.YES_NO_OPTION);
            if (answer == JOptionPane.YES_OPTION) {
                btnLogoutActionPerformed(null);
            }
        } else {
            closeDialog(dialog);
        }
    }

    private void confirmExit() {
        int answer = JOptionPane.showConfirmDialog(this, "Vai tiešām vēlaties aizvērt programmu?",
                "Programmas aizvēršana", JOptionPane.YES_NO_OPTION);
        if (answer == JOptionPane.YES_OPTION) {
            DatabaseManager.shutdown();
            dispose();
            System.exit(0);
        }
    }

    /**
     * Rekursīvi attīra visus teksta laukus norādītajā konteinerā.
     *
     * @param container konteiners, kura ievadlauki jāattīra
     */
    private void clearInputs(Container container) {
        for (Component c : container.getComponents()) {
            if (c instanceof JTextComponent) {
                ((JTextComponent) c).setText("");
            } else if (c instanceof Container) {
                clearInputs((Container) c);
            }
        }
    }

