    private void btnAddScreeningActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddScreeningActionPerformed
        if (!requireAdmin(ScreeningDialog)) {
            return;
        }
        Hall hall = (Hall) cmbHall.getSelectedItem();
        LocalDate date = Validator.parseDate(txtScreeningDate.getText());
        LocalTime time = Validator.parseTime(txtScreeningTime.getText());
        BigDecimal price = Validator.parsePrice(txtPrice.getText());
        if (hall == null) {
            showError(ScreeningDialog, "Izvēlieties zāli.");
        } else if (date == null) {
            showError(ScreeningDialog, "Datums jānorāda formātā gggg-mm-dd (piemēram, 2030-05-17).");
        } else if (time == null) {
            showError(ScreeningDialog, "Laiks jānorāda formātā hh:mm (piemēram, 18:30).");
        } else if (price == null) {
            showError(ScreeningDialog, "Cenai jābūt pozitīvam skaitlim līdz 9999.99.");
        } else {
            try {
                screeningService.addScreening(currentMovie.getId(), hall.getId(), date, time, price);
                showInfo(ScreeningDialog, "Seanss ir pievienots.");
                txtScreeningDate.setText("");
                txtScreeningTime.setText("");
                txtPrice.setText("");
                loadScreenings();
            } catch (BusinessException e) {
                showError(ScreeningDialog, e.getMessage());
            }
        }
    }//GEN-LAST:event_btnAddScreeningActionPerformed

