    private void loadMovies(String criterion) {
        moviesModel.setRowCount(0);
        List<Movie> movies = Validator.isBlank(criterion) ? movieDAO.findAllMovies() : movieDAO.search(criterion);
        for (Movie m : movies) {
            moviesModel.addRow(new Object[]{m.getId(), m.getTitle(), m.getGenre(), m.getDurationMin(),
                m.getDescription()});
        }
    }

    /**
     * Ielādē tabulā izvēlētās filmas seansus. Klientam tiek rādīti tikai vēl nesākušies seansi, administratoram visi.
     */
    private void loadScreenings() {
        screeningsModel.setRowCount(0);
        Map<Integer, Hall> halls = new HashMap<>();
        for (Hall h : hallDAO.findAllHalls()) {
            halls.put(h.getId(), h);
        }
        LocalDateTime now = LocalDateTime.now();
        for (Screening s : screeningDAO.findByMovie(currentMovie.getId())) {
            if (!Session.isAdmin() && !s.getStartDateTime().isAfter(now)) {
                continue;
            }
            Hall hall = halls.get(s.getHallId());
            int free = seatDAO.findFreeSeats(s.getId()).size();
            screeningsModel.addRow(new Object[]{s.getId(), hall == null ? "" : hall.getName(), s.getDate().toString(),
                s.getTime().toString(), s.getPrice().toPlainString(),
                free + " / " + (hall == null ? "?" : hall.getSeatCount())});
        }
    }

    /**
     * Ielādē rezervācijas tabulā: klientam - viņa paša, administratoram - visas.
     */
    private void loadReservations() {
        reservationsModel.setRowCount(0);
        List<ReservationView> list = Session.isAdmin()
                ? reservationDAO.findAllViews() : reservationDAO.findViewsByUser(Session.userId);
        for (ReservationView v : list) {
            reservationsModel.addRow(new Object[]{v.getId(), v.getUsername(), v.getMovieTitle(), v.getHallName(),
                v.getDate().toString(), v.getTime().toString(), v.getSeatRow(), v.getSeatNumber(),
                "ACTIVE".equals(v.getStatus()) ? "Aktīva" : "Atcelta", v.getDeposit().toPlainString()});
        }
    }

    /**
     * Pārbauda filmas ievadītos datus un izveido filmas objektu; kļūdas gadījumā parāda ziņojumu.
     *
     * @param parent logs, virs kura rādīt kļūdas
     * @param title nosaukums
     * @param genre žanrs
     * @param duration ilgums minūtēs (teksts)
     * @param description apraksts
     * @return filma vai null, ja dati nav derīgi
     */
    private Movie readMovieInput(Component parent, String title, String genre, String duration, String description) {
        if (Validator.isBlank(title)) {
            showError(parent, "Filmas nosaukums nedrīkst būt tukšs.");
            return null;
        }
        if (title.trim().length() > 100 || genre.trim().length() > 50 || description.trim().length() > 500) {
            showError(parent, "Teksts ir pārāk garš (nosaukums līdz 100, žanrs līdz 50, apraksts līdz 500 rakstzīmēm).");
            return null;
        }
        Integer minutes = Validator.parsePositiveInt(duration);
        if (minutes == null) {
            showError(parent, "Ilgumam jābūt pozitīvam veselam skaitlim (minūtēs).");
            return null;
        }
        return new Movie(title.trim(), genre.trim(), minutes, description.trim());
    }

    /**
     * Uzzīmē zāles vietu shēmu izvēlētajam seansam: zaļa - brīva, sarkana - aizņemta, zila - izvēlēta.
     */
    private void buildSeatMap() {
        selectedSeat = null;
        selectedSeatButton = null;
        lblSelectedSeat.setText("Izvēlētā vieta: nav izvēlēta");
        pnlSeats.removeAll();
        List<Seat> seats = seatDAO.findByHall(currentScreening.getHallId());
        Set<Integer> taken = reservationDAO.findTakenSeatIds(currentScreening.getId());
        int rows = 1;
        int cols = 1;
        Map<Integer, Seat> byPosition = new HashMap<>();
        for (Seat s : seats) {
            rows = Math.max(rows, s.getSeatRow());
            cols = Math.max(cols, s.getSeatNumber());
            byPosition.put(s.getSeatRow() * 1000 + s.getSeatNumber(), s);
        }
        pnlSeats.setLayout(new GridLayout(rows, cols, 4, 4));
        for (int r = 1; r <= rows; r++) {
            for (int n = 1; n <= cols; n++) {
                final Seat seat = byPosition.get(r * 1000 + n);
                if (seat == null) {
                    pnlSeats.add(new javax.swing.JLabel());
                    continue;
                }
                final SeatButton button = new SeatButton(String.valueOf(n), taken.contains(seat.getId()) ? SEAT_TAKEN : SEAT_FREE);
                button.setToolTipText(seat.toString());
                if (taken.contains(seat.getId())) {
                    button.setEnabled(false);
                } else {
                    button.addActionListener(new java.awt.event.ActionListener() {
                        public void actionPerformed(java.awt.event.ActionEvent evt) {
                            selectSeat(seat, button);
                        }
                    });
                }
                pnlSeats.add(button);
            }
        }
        pnlSeats.revalidate();
        pnlSeats.repaint();
    }

    private void selectSeat(Seat seat, SeatButton button) {
        if (selectedSeatButton != null) {
            selectedSeatButton.setFill(SEAT_FREE);
        }
        selectedSeat = seat;
        selectedSeatButton = button;
        button.setFill(SEAT_SELECTED);
        lblSelectedSeat.setText("Izvēlētā vieta: " + seat);
    }

